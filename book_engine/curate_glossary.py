def main():
    engine_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(engine_dir, 'glossary_data.json')

    by_unit = {}
    for g in CURATED_GLOSSES:
        uid = g["unit_id"]
        if uid not in by_unit:
            by_unit[uid] = []
        by_unit[uid].append({
            "id": g["id"],
            "term": g["term"],
            "pattern": g["pattern"],
            "gloss": g["gloss"],
        })

    payload = {
        "source_credit": SOURCE_CREDIT,
        "count": len(CURATED_GLOSSES),
        "by_unit": by_unit,
    }

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)

    print(f"Saved {len(CURATED_GLOSSES)} curated glosses across {len(by_unit)} units to {out_path}")


if __name__ == "__main__":
    main()
